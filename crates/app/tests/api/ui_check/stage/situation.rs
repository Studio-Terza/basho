use std::fmt;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Situation {
    LegStart,
    WaitingForRide,
    WalkingWithGps,
    OffRoute,
    Late,
    BrowsingWhileLate,
    WeekEarly,
    DayDone,
    LocationProblem,
    MenuOpen,
    BrowsingNextDay,
    BrowsingDayBefore,
    BrowsingMidDay,
    MenuJump,
    WikiPage,
    CameFromWiki,
    ReportsPage,
    ReportsEmpty,
    TripPicker,
    TripRefused,
    BufferComfortable,
    BufferTight,
    BufferShort,
    BufferCutoff,
    GoalBuffers,
    BrowsingWhileShort,
    Stopped,
    MapKey,
    Exploring,
}

impl fmt::Display for Situation {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str(match self {
            Situation::LegStart => "at a step start",
            Situation::WaitingForRide => "waiting for the ride",
            Situation::WalkingWithGps => "walking with GPS and compass",
            Situation::OffRoute => "off the route",
            Situation::Late => "late",
            Situation::BrowsingWhileLate => "browsing while late",
            Situation::WeekEarly => "a week early",
            Situation::DayDone => "day done",
            Situation::LocationProblem => "location",
            Situation::MenuOpen => "menu open",
            Situation::BrowsingNextDay => "browsing the next day",
            Situation::BrowsingDayBefore => "browsing the day before",
            Situation::BrowsingMidDay => "browsing a mid-day step",
            Situation::MenuJump => "menu jump",
            Situation::WikiPage => "wiki page",
            Situation::CameFromWiki => "came from a wiki page",
            Situation::ReportsPage => "bug reports page",
            Situation::ReportsEmpty => "no bug reports yet",
            Situation::TripPicker => "trip picker",
            Situation::TripRefused => "trip picker with a refused file",
            Situation::BufferComfortable => "buffer comfortable",
            Situation::BufferTight => "buffer tight",
            Situation::BufferShort => "buffer short with a backup ride",
            Situation::BufferCutoff => "buffer on a closing time",
            Situation::GoalBuffers => "goal buffers",
            Situation::BrowsingWhileShort => "browsing while short",
            Situation::Stopped => "stopped at a planned stop",
            Situation::MapKey => "map key and a tapped marker",
            Situation::Exploring => "exploring the map",
        })
    }
}
